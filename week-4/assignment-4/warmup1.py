# Warmup1: List Operations
# Creating a Hardcoded list of 8 numbers without using loops, print.

numbers = [3, 5, 2, 4, 1, 8, 9, 7]
print(numbers)

# The first item
print(f"First: {numbers[0]}")

# The last item
print(f"Last: {numbers[-1]}")

# The Middle four items
print(f"Middle four: {numbers[2:6]}")

# The List reversed
print(f"Reversed: {numbers[::-1]}")